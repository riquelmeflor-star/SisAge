CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    cargo VARCHAR(20) NOT NULL DEFAULT 'docente'
        CHECK (cargo IN ('docente', 'coordenador', 'admin', 'superadmin')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS usuarios_cargo_check;
ALTER TABLE usuarios ADD CONSTRAINT usuarios_cargo_check
    CHECK (cargo IN ('docente', 'coordenador', 'admin', 'superadmin'));

CREATE UNIQUE INDEX IF NOT EXISTS idx_usuario_unico_superadmin
    ON usuarios (cargo) WHERE cargo = 'superadmin';

CREATE TABLE IF NOT EXISTS tokens_cadastro (
    token_hash CHAR(64) PRIMARY KEY,
    criado_por BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '24 hours'),
    utilizado_em TIMESTAMPTZ,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS tentativas_cadastro (
    ip_hash CHAR(64) PRIMARY KEY,
    tentativas INTEGER NOT NULL DEFAULT 0,
    inicio_janela TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS recursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    categoria VARCHAR(30) NOT NULL
        CHECK (categoria IN ('laboratorio', 'projetor', 'som', 'kit_multimidia')),
    descricao VARCHAR(255),
    capacidade INTEGER NOT NULL DEFAULT 0 CHECK (capacidade >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'disponivel'
        CHECK (status IN ('disponivel', 'manutencao', 'indisponivel')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    recurso_id BIGINT NOT NULL REFERENCES recursos(id) ON DELETE CASCADE,
    data_reserva DATE NOT NULL,
    horario_inicio TIME NOT NULL,
    horario_fim TIME NOT NULL,
    disciplina VARCHAR(100) NOT NULL,
    turma VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'confirmada'
        CHECK (status IN ('confirmada', 'cancelada', 'pendente')),
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_horario_reserva CHECK (horario_fim > horario_inicio)
);

CREATE INDEX IF NOT EXISTS idx_recurso_categoria ON recursos(categoria);
CREATE INDEX IF NOT EXISTS idx_recurso_status ON recursos(status);
CREATE INDEX IF NOT EXISTS idx_reserva_data ON reservas(data_reserva);
CREATE INDEX IF NOT EXISTS idx_reserva_status ON reservas(status);

